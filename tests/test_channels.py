"""Bad-channel assessment, marking, and interpolation on planted synthetic faults."""

import json

import mne
import numpy as np
import pytest

from eeg_decoder.artifacts import (
    ChannelAssessment,
    assess_channels,
    interpolate_bad_channels,
    mark_bad_channels,
)
from eeg_decoder.io import to_raw
from eeg_decoder.preprocessing import EEGPipeline, PreprocessingConfig, bandpass

NAMES = ["Fp1", "Fp2", "F3", "F4", "F7", "F8", "Fz", "C3", "C4", "Cz",
         "T7", "T8", "P3", "P4", "Pz", "O1"]
SF, N = 250.0, 250 * 30
MONTAGE = "colin27_1020"


def _recording(plant=True, seed=0, extra_types=False):
    """16 channels mixing 3 shared rhythms (so neighbours correlate) + sensor noise.

    Planted faults: F8 flat, T7 loose (10x amplitude), O1 replaced by
    uncorrelated noise of the same amplitude, P4 with added broadband noise.
    """
    rng = np.random.default_rng(seed)
    t = np.arange(N) / SF
    src = np.vstack([np.sin(2 * np.pi * f * t + rng.uniform(0, 6)) for f in (6, 10, 18)])
    src += 0.5 * rng.normal(size=src.shape)
    x = 10e-6 * (rng.uniform(0.5, 1.5, (16, 3)) @ src) / 3 + rng.normal(0, 1e-6, (16, N))
    if plant:
        i = NAMES.index
        x[i("F8")] = 0.0
        x[i("T7")] *= 10
        x[i("O1")] = rng.normal(0, x[i("O1")].std(), N)
        x[i("P4")] += rng.normal(0, 4e-6, N)
    names, types = list(NAMES), ["eeg"] * 16
    if extra_types:
        x = np.vstack([x, rng.normal(0, 50e-6, (1, N)), np.zeros((1, N))])
        names += ["EOG", "STI"]
        types += ["eog", "stim"]
    return bandpass(to_raw(x, SF, names, types), 1.0, None, picks="eeg")


def _smooth_field_raw():
    """EEG generated by a spatially smooth field, so interpolation can be checked."""
    info = mne.create_info(NAMES, SF, "eeg")
    info.set_montage(MONTAGE)
    pos = np.array([ch["loc"][:3] for ch in info["chs"]])
    pos = pos / np.linalg.norm(pos, axis=1, keepdims=True)
    rng = np.random.default_rng(1)
    t = np.arange(N) / SF
    tc = np.vstack([np.sin(2 * np.pi * f * t) for f in (5, 9, 13)])
    x = 10e-6 * (pos @ rng.normal(size=(3, 3))) @ tc  # linear field over the sphere
    raw = mne.io.RawArray(x, info, verbose="error")
    return raw


# --- assessment -------------------------------------------------------------


def test_clean_recording_has_no_bad_channels():
    a = assess_channels(_recording(plant=False))
    assert a.bad == () and a.reasons == {} and a.skipped == {}
    assert a.channels == tuple(NAMES)


def test_each_planted_fault_is_found_with_its_reason():
    a = assess_channels(_recording())
    assert a.bad == ("F8", "T7", "P4", "O1")  # recording order
    assert a.reasons["F8"] == ("flat",)
    assert a.reasons["T7"] == ("deviation",)
    assert a.reasons["P4"] == ("hf_noise",)
    assert "correlation" in a.reasons["O1"]
    assert a.metrics["deviation"]["T7"] > 5
    assert a.metrics["correlation"]["O1"] == 1.0  # poorly correlated in every window
    assert np.isnan(a.metrics["deviation"]["F8"])  # flat channels excluded from statistics


def test_assessment_never_changes_data():
    raw = _recording()
    before, bads = raw.get_data().copy(), list(raw.info["bads"])
    assess_channels(raw)
    np.testing.assert_array_equal(raw.get_data(), before)
    assert raw.info["bads"] == bads


def test_only_eeg_channels_assessed_and_previous_bads_reported():
    raw = _recording(extra_types=True)
    raw.info["bads"] = ["Cz", "EOG"]
    a = assess_channels(raw)
    assert "EOG" not in a.channels and "STI" not in a.channels
    assert a.previously_bad == ("Cz",)


def test_hf_criterion_skipped_without_high_frequency_content():
    a = assess_channels(bandpass(_recording(), 1.0, 40.0))
    assert "hf_noise" in a.skipped and "lowpass=40" in a.skipped["hf_noise"]
    assert "P4" not in a.bad  # its only evidence was high-frequency noise
    assert {"F8", "T7", "O1"} <= set(a.bad)


def test_nan_channel():
    raw = _recording(plant=False)
    raw._data[2, 100:110] = np.nan
    a = assess_channels(raw)
    assert a.reasons["F3"] == ("nan",)


def test_short_recording_skips_correlation():
    raw = _recording(plant=False).crop(tmax=0.5)
    a = assess_channels(raw)
    assert "correlation" in a.skipped and "shorter than one" in a.skipped["correlation"]


def test_report_is_json_serializable_and_deterministic():
    a1, a2 = assess_channels(_recording()), assess_channels(_recording())
    d = a1.to_dict()
    assert json.loads(json.dumps(d, allow_nan=False)) == d
    assert d == a2.to_dict()
    assert d["metrics"]["deviation"]["F8"] is None
    assert "T7: deviation" in a1.summary()


def test_report_is_immutable():
    a = assess_channels(_recording())
    assert isinstance(a, ChannelAssessment)
    with pytest.raises(TypeError):
        a.reasons["Fz"] = ("flat",)
    with pytest.raises(AttributeError):
        a.bad = ()


@pytest.mark.parametrize(
    "kwargs, exc",
    [({"flat_threshold": 0}, ValueError), ({"deviation_threshold": -1}, ValueError),
     ({"correlation_threshold": 1.0}, ValueError), ({"max_low_correlation_fraction": 1.5}, ValueError),
     ({"correlation_window_s": np.inf}, ValueError), ({"hf_noise_threshold": "5"}, TypeError)],
)
def test_invalid_thresholds(kwargs, exc):
    with pytest.raises(exc):
        assess_channels(_recording(plant=False), **kwargs)


def test_invalid_inputs():
    with pytest.raises(ValueError, match="at least 3"):
        assess_channels(to_raw(np.zeros((2, 500)), SF, ["Cz", "Pz"]))
    with pytest.raises(TypeError, match="continuous"):
        assess_channels(np.zeros((16, 500)))
    raw = _recording(plant=False)
    epochs = mne.make_fixed_length_epochs(raw, 1.0, preload=True, verbose="error")
    with pytest.raises(TypeError, match="continuous"):
        assess_channels(epochs)


# --- marking ----------------------------------------------------------------


def test_mark_adds_in_recording_order_and_copies():
    raw = _recording()
    raw.info["bads"] = ["Pz"]
    out = mark_bad_channels(raw, ["O1", "T7"])
    assert out.info["bads"] == ["T7", "Pz", "O1"]
    assert raw.info["bads"] == ["Pz"]
    np.testing.assert_array_equal(out.get_data(), raw.get_data())


def test_mark_replace_and_empty():
    raw = _recording()
    raw.info["bads"] = ["Pz"]
    assert mark_bad_channels(raw, ["T7"], replace=True).info["bads"] == ["T7"]
    assert mark_bad_channels(raw, []).info["bads"] == ["Pz"]
    assert mark_bad_channels(raw, [], replace=True).info["bads"] == []


def test_mark_from_assessment_round_trip():
    raw = _recording()
    out = mark_bad_channels(raw, assess_channels(raw).bad)
    assert out.info["bads"] == ["F8", "T7", "P4", "O1"]


@pytest.mark.parametrize("channels, exc", [("T7", TypeError), ([1], TypeError),
                                           (["XX"], ValueError), (["T7", "T7"], ValueError)])
def test_mark_invalid(channels, exc):
    with pytest.raises(exc):
        mark_bad_channels(_recording(), channels)


# --- interpolation ----------------------------------------------------------


def test_interpolation_reconstructs_smooth_field():
    clean = _smooth_field_raw()
    noisy = clean.copy()
    noisy._data[NAMES.index("Cz")] = np.random.default_rng(2).normal(0, 50e-6, N)
    out = interpolate_bad_channels(mark_bad_channels(noisy, ["Cz"]))
    est, true = out.get_data(picks="Cz")[0], clean.get_data(picks="Cz")[0]
    assert np.corrcoef(est, true)[0, 1] > 0.99
    others = [i for i in range(16) if NAMES[i] != "Cz"]
    np.testing.assert_array_equal(out.get_data()[others], noisy.get_data()[others])
    assert out.info["bads"] == []


def test_interpolation_keeps_bads_when_asked_and_keeps_non_eeg_bads():
    raw = _smooth_field_raw()
    raw.add_channels([mne.io.RawArray(np.zeros((1, N)), mne.create_info(["EOG"], SF, "eog"),
                                      verbose="error")])
    raw.info["bads"] = ["Cz", "EOG"]
    out = interpolate_bad_channels(raw)
    # MNE alone would silently drop "EOG" from bads (or refuse with "raise").
    assert out.info["bads"] == ["EOG"]
    np.testing.assert_array_equal(out.get_data(picks="EOG"), raw.get_data(picks="EOG"))
    plain = raw.copy().interpolate_bads(verbose="error")  # pins the MNE behaviour we work around
    assert "EOG" not in plain.info["bads"]
    assert interpolate_bad_channels(raw, reset_bads=False).info["bads"] == ["Cz", "EOG"]


def test_interpolation_works_on_epochs():
    raw = mark_bad_channels(_smooth_field_raw(), ["Pz"])
    epochs = mne.make_fixed_length_epochs(raw, 1.0, preload=True, verbose="error")
    out = interpolate_bad_channels(epochs)
    assert isinstance(out, mne.BaseEpochs) and out.info["bads"] == []


def test_no_bad_eeg_channels_returns_unchanged_copy():
    raw = _smooth_field_raw()
    out = interpolate_bad_channels(raw)
    assert out is not raw
    np.testing.assert_array_equal(out.get_data(), raw.get_data())


def test_interpolation_requires_positions():
    raw = mark_bad_channels(_recording(plant=False), ["Cz"])  # no montage
    with pytest.raises(ValueError, match="colin27_1020"):
        interpolate_bad_channels(raw)


def test_interpolation_refuses_too_many_bads():
    raw = mark_bad_channels(_smooth_field_raw(), NAMES[:4])  # 25 %
    with pytest.raises(ValueError, match="max_fraction"):
        interpolate_bad_channels(raw)
    interpolate_bad_channels(raw, max_fraction=0.3)  # explicit opt-in


@pytest.mark.parametrize("max_fraction, exc", [(0, ValueError), (1.0, ValueError), ("0.2", TypeError)])
def test_interpolation_invalid_max_fraction(max_fraction, exc):
    with pytest.raises(exc):
        interpolate_bad_channels(_smooth_field_raw(), max_fraction=max_fraction)


def test_interpolation_input_untouched():
    raw = mark_bad_channels(_smooth_field_raw(), ["Cz"])
    before = raw.get_data().copy()
    interpolate_bad_channels(raw)
    np.testing.assert_array_equal(raw.get_data(), before)
    assert raw.info["bads"] == ["Cz"]


# --- pipeline integration ---------------------------------------------------


def test_interpolation_as_pipeline_step_before_average_reference():
    raw = mark_bad_channels(_smooth_field_raw(), ["Cz"])
    cfg = PreprocessingConfig([
        {"op": "interpolate_bad_channels", "max_fraction": 0.2},
        {"op": "rereference", "ref": "average"},
    ])
    out, record = EEGPipeline(cfg).run(raw)
    assert out.info["bads"] == [] and out.info["custom_ref_applied"]
    assert record["input"]["bads"] == ["Cz"]
    assert record["steps"][0]["output"]["bads"] == []
